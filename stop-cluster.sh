#!/bin/bash
# ================================================================
# 10만명 동시접속 채팅방 - 클러스터 중지 스크립트
# ================================================================

set -e

echo "========================================"
echo "🛑 10만명 동시접속 채팅 클러스터 중지"
echo "========================================"
echo ""

# 옵션 확인
REMOVE_VOLUMES=false
if [ "$1" == "-v" ] || [ "$1" == "--volumes" ]; then
    REMOVE_VOLUMES=true
    echo "⚠️  볼륨도 함께 삭제됩니다!"
    echo ""
fi

# 확인
if [ "$REMOVE_VOLUMES" = true ]; then
    read -p "정말로 볼륨을 포함해서 모두 삭제하시겠습니까? 데이터가 영구 삭제됩니다! (y/N) " -n 1 -r
    echo
    if [[ ! $REPLY =~ ^[Yy]$ ]]; then
        echo "❌ 중지 취소됨"
        exit 1
    fi
fi

# ----------------------------------------------------------------
# 1️⃣ 컨테이너 중지
# ----------------------------------------------------------------
echo "1️⃣ 컨테이너 중지 중..."
echo ""

if [ "$REMOVE_VOLUMES" = true ]; then
    docker-compose down -v
    echo "✅ 컨테이너 및 볼륨 삭제 완료"
else
    docker-compose down
    echo "✅ 컨테이너 중지 완료 (볼륨 유지)"
fi

# ----------------------------------------------------------------
# 2️⃣ 정리 완료
# ----------------------------------------------------------------
echo ""
echo "========================================"
echo "✅ 클러스터 중지 완료!"
echo "========================================"
echo ""

if [ "$REMOVE_VOLUMES" = false ]; then
    echo "ℹ️  데이터는 보존되었습니다."
    echo "   다시 시작: ./start-cluster.sh"
    echo ""
    echo "💡 완전 삭제 (볼륨 포함):"
    echo "   ./stop-cluster.sh -v"
else
    echo "⚠️  모든 데이터가 삭제되었습니다."
    echo "   다시 시작: ./start-cluster.sh"
fi

echo ""
echo "📊 상태 확인:"
echo "   docker-compose ps"
echo "   docker volume ls"
echo ""



